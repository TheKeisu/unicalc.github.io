export function periodByNumber(number) {
  if (number <= 2) return 1;
  if (number <= 10) return 2;
  if (number <= 18) return 3;
  if (number <= 36) return 4;
  if (number <= 54) return 5;
  if (number <= 86) return 6;
  return 7;
}

export function groupByNumber(number) {
  for (const row of Object.values(MAIN_TABLE_LAYOUT)) {
    const index = row.indexOf(number);
    if (index !== -1) return index + 1;
  }
  if (number >= 58 && number <= 71) return 'Ln';
  if (number >= 90 && number <= 103) return 'An';
  return '—';
}

export function blockByNumber(number) {
  if ((number >= 58 && number <= 71) || (number >= 90 && number <= 103)) return 'f';
  if ([1, 2, 3, 4, 11, 12, 19, 20, 37, 38, 55, 56, 87, 88].includes(number)) return 's';
  if (
    (number >= 21 && number <= 30) ||
    (number >= 39 && number <= 48) ||
    (number >= 72 && number <= 80) ||
    (number >= 104 && number <= 112)
  ) return 'd';
  return 'p';
}
